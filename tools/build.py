"""Build the restructured, expanded SIP report.

  python3 tools/build.py
"""
import os, re, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import docxkit as K
import engine as E
import plan_a, plan_b

SRC = 'SIP - M16158 NIkhil Singh.docx'
DST = 'SIP - M16158 Nikhil Singh - FINAL.docx'


# --------------------------------------------------------------------------
# page-count estimator, calibrated against the original file (79 pages)
# --------------------------------------------------------------------------
PAGE_POINTS = 714.0          # 16834 - 1250 - 1300 twips of usable height
LINE_PT = 15.9               # 12 pt Times New Roman at 1.15 line spacing
SMALL_LINE_PT = 13.3         # 10 pt text at single spacing inside tables
CHARS_PER_LINE = 92.0        # across the 10095-twip text column at 12 pt


BK = re.compile(r'<w:bookmarkStart w:id="\d+" w:name="(_Rpt\d+)"/>')


def estimate_pages(blocks, marks=None):
    total = 0.0
    for b in blocks:
        if not b or b.startswith('<!--'):
            continue
        if marks is not None and '_Rpt' in b:
            snap = total
            if 'pageBreakBefore' in b or 'w:type="page"' in b:
                snap = (int(total / PAGE_POINTS) + 1) * PAGE_POINTS
            pg = int(snap / PAGE_POINTS) + 1
            for name in BK.findall(b):
                marks[name] = pg
        if b.startswith('<w:tbl'):
            # one pass per row, height driven by the fullest cell
            for tr in re.findall(r'<w:tr\b.*?</w:tr>', b, re.S):
                cells = re.findall(r'<w:tc>.*?</w:tc>', tr, re.S)
                h = 0
                for tc in cells:
                    wm = re.search(r'<w:tcW w:w="(\d+)"', tc)
                    width = int(wm.group(1)) if wm else 2000
                    txt = ''.join(re.findall(r'<w:t(?:\s[^>]*)?>(.*?)</w:t>', tc, re.S))
                    cpl = max(6.0, width / 55.0)       # 10 pt chars per twip-width
                    h = max(h, max(1, int(len(txt) / cpl) + 1))
                total += h * SMALL_LINE_PT + 7.5
            total += 8
            continue
        txt = ''.join(re.findall(r'<w:t(?:\s[^>]*)?>(.*?)</w:t>', b, re.S))
        if '<w:drawing>' in b:
            m = re.search(r'<wp:extent cx="(\d+)" cy="(\d+)"', b)
            if m:
                total += int(m.group(2)) / 12700.0 + 10
            continue
        szm = re.search(r'<w:sz w:val="(\d+)"', b)
        sz = int(szm.group(1)) / 2.0 if szm else 12.0
        cpl = CHARS_PER_LINE * (12.0 / sz)
        lines = max(1, int(len(txt) / cpl) + (1 if len(txt) % cpl else 0))
        lh = LINE_PT * (sz / 12.0)
        after = 6.0
        am = re.search(r'w:after="(\d+)"', b)
        if am:
            after = int(am.group(1)) / 20.0
        before = 0.0
        bm = re.search(r'w:before="(\d+)"', b)
        if bm:
            before = int(bm.group(1)) / 20.0
        if 'pageBreakBefore' in b or 'w:type="page"' in b:
            total = (int(total / PAGE_POINTS) + 1) * PAGE_POINTS
        total += lines * lh + after + before
    return int(round(total / PAGE_POINTS)) + 1


def calibrate():
    """Sanity-check the estimator against the untouched original."""
    blocks = [b['xml'] for b in E.RAW if b['kind'] != 'sectPr']
    return estimate_pages(blocks)


# --------------------------------------------------------------------------
def main():
    d = E.Doc()
    plan_a.build(d)
    plan_b.build(d)

    # ---- fill the index / list of tables / list of figures --------------
    # Two passes: the first lays the document out with empty page cells to
    # find where every bookmark falls, the second writes those numbers into
    # the PAGEREF fields as their cached result.  Word recomputes them
    # exactly whenever fields are updated or the file is printed.
    def assemble(pages):
        index_xml = (K.chapter('INDEX') + E.build_index(d, pages))
        lot_xml = (K.chapter('LIST OF TABLES')
                   + E.build_list_of(d.tables, 'TABLE NO.', 'TITLE', pages))
        lof_xml = (K.chapter('LIST OF FIGURES')
                   + E.build_list_of(d.figures, 'FIGURE NO.', 'TITLE', pages))
        out = []
        for b in d.out:
            if b == '<!--INDEX-->':
                out.append(index_xml)
            elif b == '<!--LOT-->':
                out.append(lot_xml)
            elif b == '<!--LOF-->':
                out.append(lof_xml)
            else:
                out.append(b)
        return out

    marks = {}
    estimate_pages(assemble(None), marks)
    blocks = assemble(marks)

    # ---- coverage check: nothing from the original may be lost ----------
    allowed_missing = set()
    # old chapter banners, headings, straplines, captions and the old index
    # are intentionally regenerated by the new structure
    for i, it in enumerate(E.CONTENT):
        if it['k'] != 'p':
            continue
        runs = it['runs']
        sz = runs[0]['sz'] if runs else None
        txt = it['text'].strip()
        if it['style'].startswith('Heading'):
            allowed_missing.add(i)
        elif sz in (14.0, 15.0) and (runs and runs[0]['b']):
            allowed_missing.add(i)
        elif re.match(r'^(Table|Exhibit|Figure|APPENDIX)\b', txt):
            allowed_missing.add(i)      # caption / banner - renumbered
        elif txt.isupper() and len(txt) < 60:
            allowed_missing.add(i)      # pseudo strap-line
        elif txt.startswith('Source /'):
            allowed_missing.add(i)      # source note rewritten with the table
    for i in range(0, 43):
        allowed_missing.add(i)          # front matter copied raw
    for i in range(43, 49):
        allowed_missing.add(i)          # reading conventions copied raw
    missing = [i for i in range(len(E.CONTENT))
               if i not in d.used and i not in allowed_missing]
    if missing:
        print('WARNING - original content items not re-homed:')
        for i in missing:
            it = E.CONTENT[i]
            if it['k'] == 't':
                prev = ' | '.join(it['rows'][0])
            else:
                prev = it.get('text') or ('[image %s]' % it.get('img'))
            print('   %4d  %s  %s' % (i, it['k'], prev[:90]))

    words = 0
    for b in blocks:
        words += len(''.join(re.findall(r'<w:t(?:\s[^>]*)?>(.*?)</w:t>', b, re.S)).split())

    pages = estimate_pages(blocks)
    base = calibrate()
    scaled = int(round(pages * 79.0 / base)) if base else pages

    E.write_docx(SRC, DST, blocks, words=words, pages=scaled)

    print('-' * 68)
    print('estimator calibration : original renders as %d (actual 79)' % base)
    print('new document          : %d raw / %d calibrated pages' % (pages, scaled))
    print('words                 : %d  (original 21,548)' % words)
    print('tables                : %d   figures: %d' % (len(d.tables), len(d.figures)))
    print('index entries         : %d   page refs resolved: %d'
          % (len(d.toc), len(marks)))
    print('written               : %s' % DST)


if __name__ == '__main__':
    main()
